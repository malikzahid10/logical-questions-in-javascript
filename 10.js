// 10. Convert Celsius to Fahrenheit.

// Temperature ko Celsius se Fahrenheit mein convert karne ka formula:

// F = (C * 9/5) + 32

// Yahan:
//  C = Celsius
//  F = Fahrenheit
// Example: Celsius = 30

// F = (30 *9/5) + 32 = 86

// 2. JavaScript Code
let celsius = 30;

let fahrenheit = (celsius * 9) / 5 + 32;

console.log(`Fahrenheit = ${fahrenheit}`);
